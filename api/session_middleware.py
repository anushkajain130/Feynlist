"""
Session middleware (pure ASGI, so it covers HTTP and the websocket)
==================================================================
- Reads the browser time zone (X-Feynlist-TZ header, or ?tz= on the websocket)
  for every request, so "today" and "past task" use the evaluator's clock.
- In DEMO_MODE, reads the evaluator session id (X-Feynlist-Session header, or
  ?session= on the websocket). Each session gets its own throwaway database,
  seeded with labelled sample data on first use, and its own agent state.
  Requests to /api/* without a valid session id are rejected with 400.

The id is generated by the browser (no cookies: the frontend and backend are on
different domains, and third-party cookies are often blocked).
"""

from __future__ import annotations

import asyncio
import json
from urllib.parse import parse_qs

from loguru import logger

from config.settings import settings
from core.clock import is_valid_timezone
from core.session import current_session_id, current_timezone, is_valid_session_id

_init_locks: dict[str, asyncio.Lock] = {}


async def ensure_session_ready(session_id: str, force_reseed: bool = False) -> None:
    """Create, migrate and (first time only) seed the session's database."""
    from data.database import session_databases
    from demo.sample_data import seed_all

    lock = _init_locks.setdefault(session_id, asyncio.Lock())
    async with lock:
        database, created = session_databases.get(session_id)
        if not database.is_initialized():
            await database.initialize()
        if created or force_reseed:
            logger.info(f"Demo: seeding sample data for session {session_id[:8]}…")
            await seed_all()


class SessionMiddleware:
    EXEMPT = {"/", "/health", "/docs", "/redoc", "/openapi.json"}

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope["type"] not in ("http", "websocket"):
            return await self.app(scope, receive, send)

        headers = {k.decode("latin-1").lower(): v.decode("latin-1") for k, v in scope.get("headers", [])}
        query = parse_qs(scope.get("query_string", b"").decode("latin-1"))
        tz = headers.get("x-feynlist-tz") or (query.get("tz") or [None])[0]
        sid = headers.get("x-feynlist-session") or (query.get("session") or [None])[0]

        tz_token = current_timezone.set(tz if is_valid_timezone(tz) else None)
        sid_token = None
        try:
            path = scope.get("path", "")
            needs_session = settings.demo_mode and path.startswith("/api/") and path not in self.EXEMPT
            if needs_session:
                if scope["type"] == "http" and scope.get("method") == "OPTIONS":
                    return await self.app(scope, receive, send)  # CORS preflight
                if not is_valid_session_id(sid):
                    return await self._reject(scope, send)
                sid_token = current_session_id.set(sid)
                await ensure_session_ready(sid)
            await self.app(scope, receive, send)
        finally:
            if sid_token is not None:
                current_session_id.reset(sid_token)
            current_timezone.reset(tz_token)

    @staticmethod
    async def _reject(scope, send):
        if scope["type"] == "websocket":
            await send({"type": "websocket.close", "code": 4400})
            return
        body = json.dumps({"detail": "Missing or invalid demo session. Please reload the page."}).encode()
        await send({"type": "http.response.start", "status": 400,
                    "headers": [(b"content-type", b"application/json"),
                                (b"content-length", str(len(body)).encode())]})
        await send({"type": "http.response.body", "body": body})
