"""
Request-scoped session context
==============================
Holds the evaluator session id and browser time zone for the current request
(set by api.session_middleware). Code that needs per-session state (database,
agent runtimes, clock) reads these instead of globals.

Outside a request (scheduler, scripts, tests) both are None, which means
"single-user mode": the default database and the server's time zone.
"""

from __future__ import annotations

import re
from contextvars import ContextVar

current_session_id: ContextVar[str | None] = ContextVar("current_session_id", default=None)
current_timezone: ContextVar[str | None] = ContextVar("current_timezone", default=None)

# Session ids are generated by the browser: 32 lowercase hex chars (uuid4().hex).
SESSION_ID_RE = re.compile(r"^[a-f0-9]{32}$")


def is_valid_session_id(value: str | None) -> bool:
    return bool(value) and bool(SESSION_ID_RE.match(value))
